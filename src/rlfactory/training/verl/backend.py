"""verl backend: writes verl-format parquet, a reward shim and a Hydra launch command.

Verified against verl 0.9.1 (docs/references/post-training-stack.md). Uses the current
``reward.custom_reward_function.*`` keys (not the legacy top-level ones) and always sets
``actor_rollout_ref.rollout.name``. Dry-run the generated command on the GPU host first
(``python3 -m verl.trainer.main_ppo ... --cfg job``), because verl's docs lag its source.
"""

from __future__ import annotations

from pathlib import Path

import pyarrow as pa
import pyarrow.parquet as pq
from pydantic import BaseModel, ConfigDict, Field

from rlfactory.config.loader import write_json
from rlfactory.datasets.adapters import to_verl_rl
from rlfactory.domain.training import (
    GRPOParams,
    PreparedTrainingRun,
    TrainingHandle,
    TrainingMethod,
    TrainingRun,
    TrainingStatus,
)
from rlfactory.errors import ConfigError
from rlfactory.training.base import (
    LAUNCH_SCRIPT,
    RUN_CONFIG_FILE,
    render_launch_script,
    status_from_workdir,
)
from rlfactory.training.external import framework_version, load_rl_records, remote_only_launch

TARGET_VERL_VERSION = "0.9.1"
REWARD_SHIM = '''"""verl reward entry point generated by RLFactory."""
from rlfactory.training.verl.reward import compute_score  # noqa: F401
'''


class VerlSettings(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")

    rollout_engine: str = "vllm"
    n_gpus_per_node: int = Field(default=1, ge=1)
    nnodes: int = Field(default=1, ge=1)
    train_batch_size: int = Field(default=32, ge=1)
    ppo_mini_batch_size: int = Field(default=16, ge=1)
    max_prompt_length: int = Field(default=1024, ge=16)
    rollout_gpu_memory_utilization: float = Field(default=0.5, gt=0.0, lt=1.0)
    tensor_model_parallel_size: int = Field(default=1, ge=1)


class VerlTrainingBackend:
    name = "verl"

    def __init__(self, workdir_root: Path, settings: VerlSettings | None = None) -> None:
        self.workdir_root = workdir_root
        self.settings = settings or VerlSettings()

    def command(self, run: TrainingRun) -> list[str]:
        params = run.config.method_params
        if not isinstance(params, GRPOParams):  # pragma: no cover - guarded in prepare
            raise ConfigError("verl backend currently prepares GRPO runs only")
        s = self.settings
        lora = run.config.lora
        overrides = [
            "algorithm.adv_estimator=grpo",
            "algorithm.use_kl_in_reward=False",
            "data.train_files=['data/train.parquet']",
            "data.val_files=['data/train.parquet']",
            f"data.train_batch_size={s.train_batch_size}",
            f"data.max_prompt_length={s.max_prompt_length}",
            f"data.max_response_length={params.max_completion_length}",
            "data.filter_overlong_prompts=True",
            "data.truncation=error",
            f"actor_rollout_ref.model.path={run.model.name}",
            f"actor_rollout_ref.actor.optim.lr={run.config.learning_rate}",
            f"actor_rollout_ref.actor.ppo_mini_batch_size={s.ppo_mini_batch_size}",
            f"actor_rollout_ref.actor.use_kl_loss={params.beta > 0}",
            f"actor_rollout_ref.actor.kl_loss_coef={params.beta}",
            "actor_rollout_ref.actor.kl_loss_type=low_var_kl",
            f"actor_rollout_ref.rollout.name={s.rollout_engine}",
            f"actor_rollout_ref.rollout.n={params.num_generations}",
            f"actor_rollout_ref.rollout.tensor_model_parallel_size={s.tensor_model_parallel_size}",
            f"actor_rollout_ref.rollout.gpu_memory_utilization={s.rollout_gpu_memory_utilization}",
            "reward.custom_reward_function.path=reward_fn.py",
            "reward.custom_reward_function.name=compute_score",
            "reward.reward_manager.name=naive",
            f"trainer.n_gpus_per_node={s.n_gpus_per_node}",
            f"trainer.nnodes={s.nnodes}",
            f"trainer.total_epochs={max(1, int(run.config.num_train_epochs))}",
            "trainer.logger=['console']",
            "trainer.project_name=rlfactory",
            f"trainer.experiment_name={run.run_id}",
            "trainer.default_local_dir=checkpoints",
            f"trainer.save_freq={run.config.save_steps}",
        ]
        if lora.enabled:
            overrides += [
                f"actor_rollout_ref.model.lora_rank={lora.r}",
                f"actor_rollout_ref.model.lora_alpha={lora.alpha}",
                "actor_rollout_ref.model.target_modules=all-linear",
                "actor_rollout_ref.rollout.load_format=safetensors",
            ]
        return ["python3", "-m", "verl.trainer.main_ppo", *overrides]

    def prepare(self, run: TrainingRun) -> PreparedTrainingRun:
        if run.method is not TrainingMethod.GRPO:
            raise ConfigError("the verl backend prepares GRPO runs; use TRL for SFT/DPO in v0.1")
        records = load_rl_records(run)
        multi_step = [r.task.task_id for r in records if r.task.domain.value == "tool_use"]
        if multi_step:
            raise ConfigError(
                f"{len(multi_step)} multi-step tasks cannot use the single-turn reward shim"
            )
        workdir = self.workdir_root / run.run_id
        (workdir / "data").mkdir(parents=True, exist_ok=True)
        rows = [to_verl_rl(record, index) for index, record in enumerate(records)]
        pq.write_table(
            pa.Table.from_pylist(rows), workdir / "data" / "train.parquet", compression="zstd"
        )
        (workdir / "reward_fn.py").write_text(REWARD_SHIM, encoding="utf-8", newline="\n")
        write_json(run, workdir / RUN_CONFIG_FILE)
        command = self.command(run)
        (workdir / LAUNCH_SCRIPT).write_text(
            render_launch_script(command), encoding="utf-8", newline="\n"
        )
        return PreparedTrainingRun(
            run=run,
            backend=self.name,
            workdir=str(workdir),
            command=("bash", LAUNCH_SCRIPT),
            files=("data/train.parquet", "reward_fn.py", RUN_CONFIG_FILE, LAUNCH_SCRIPT),
            framework_version=framework_version("verl"),
            notes=(
                f"target verl {TARGET_VERL_VERSION}; run in verl's own environment on the GPU host",
                "dry-run first: append --cfg job to the command to print the resolved Hydra config",
            ),
        )

    def launch(self, run: PreparedTrainingRun) -> TrainingHandle:
        return remote_only_launch(run, "verl")

    def inspect(self, handle: TrainingHandle) -> TrainingStatus:
        return status_from_workdir(handle)
