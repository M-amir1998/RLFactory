"""OpenRLHF backend: prompt JSONL, reward shim and a dotted-flag ``train_ppo_ray`` command.

Verified against OpenRLHF 0.11.2, which only accepts the dotted, hierarchical flags (the flat names
``--pretrain``/``--remote_rm_url``/``--advantage_estimator`` are gone). Run
``python3 -m openrlhf.cli.train_ppo_ray --help`` on the GPU host to confirm before a real run.
"""

from __future__ import annotations

from pathlib import Path

from pydantic import BaseModel, ConfigDict, Field

from rlfactory.config.loader import write_json
from rlfactory.datasets.adapters import to_openrlhf_rl
from rlfactory.domain.training import (
    GRPOParams,
    PreparedTrainingRun,
    TrainingHandle,
    TrainingMethod,
    TrainingRun,
    TrainingStatus,
)
from rlfactory.errors import ConfigError
from rlfactory.training.base import (
    LAUNCH_SCRIPT,
    RUN_CONFIG_FILE,
    render_launch_script,
    status_from_workdir,
)
from rlfactory.training.external import (
    framework_version,
    load_rl_records,
    remote_only_launch,
    write_jsonl,
)

TARGET_OPENRLHF_VERSION = "0.11.2"
REWARD_SHIM = '''"""OpenRLHF reward entry point generated by RLFactory."""
from rlfactory.training.openrlhf.reward import reward_func  # noqa: F401
'''


class OpenRLHFSettings(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")

    ray_address: str = "http://127.0.0.1:8265"
    vllm_num_engines: int = Field(default=1, ge=1)
    vllm_tensor_parallel_size: int = Field(default=1, ge=1)
    vllm_gpu_memory_utilization: float = Field(default=0.5, gt=0.0, lt=1.0)
    max_len: int = Field(default=2048, ge=64)
    colocate_all: bool = True


class OpenRLHFTrainingBackend:
    name = "openrlhf"

    def __init__(self, workdir_root: Path, settings: OpenRLHFSettings | None = None) -> None:
        self.workdir_root = workdir_root
        self.settings = settings or OpenRLHFSettings()

    def command(self, run: TrainingRun) -> list[str]:
        params = run.config.method_params
        if not isinstance(params, GRPOParams):  # pragma: no cover - guarded in prepare
            raise ConfigError("OpenRLHF backend currently prepares GRPO runs only")
        s = self.settings
        flags = [
            "--actor.model_name_or_path",
            run.model.name,
            "--data.prompt_dataset",
            "data/prompts.jsonl",
            "--data.input_key",
            "input",
            "--data.label_key",
            "label",
            "--data.apply_chat_template",
            "--data.max_len",
            str(s.max_len),
            "--rollout.max_new_tokens",
            str(params.max_completion_length),
            "--rollout.n_samples_per_prompt",
            str(params.num_generations),
            "--algo.advantage.estimator",
            "group_norm",
            "--algo.kl.init_coef",
            str(params.beta),
            "--reward.remote_url",
            "reward_func.py",
            "--ckpt.output_dir",
            "checkpoints",
            "--vllm.num_engines",
            str(s.vllm_num_engines),
            "--vllm.tensor_parallel_size",
            str(s.vllm_tensor_parallel_size),
            "--vllm.gpu_memory_utilization",
            str(s.vllm_gpu_memory_utilization),
        ]
        if params.beta > 0:
            flags.append("--algo.kl.use_loss")
        if s.colocate_all:
            flags += ["--train.colocate_all", "--vllm.enable_sleep", "--ds.enable_sleep"]
        if run.config.lora.enabled:
            flags += [
                "--ds.lora.rank",
                str(run.config.lora.r),
                "--ds.lora.alpha",
                str(run.config.lora.alpha),
            ]
        return [
            "ray",
            "job",
            "submit",
            f"--address={s.ray_address}",
            '--runtime-env-json={"working_dir": "."}',
            "--",
            "python3",
            "-m",
            "openrlhf.cli.train_ppo_ray",
            *flags,
        ]

    def prepare(self, run: TrainingRun) -> PreparedTrainingRun:
        if run.method is not TrainingMethod.GRPO:
            raise ConfigError(
                "the OpenRLHF backend prepares GRPO runs; use TRL for SFT/DPO in v0.1"
            )
        records = load_rl_records(run)
        if any(r.task.domain.value == "tool_use" for r in records):
            raise ConfigError("multi-step tasks cannot use the single-turn reward shim")
        workdir = self.workdir_root / run.run_id
        write_jsonl(
            [to_openrlhf_rl(record) for record in records], workdir / "data" / "prompts.jsonl"
        )
        (workdir / "reward_func.py").write_text(REWARD_SHIM, encoding="utf-8", newline="\n")
        write_json(run, workdir / RUN_CONFIG_FILE)
        (workdir / LAUNCH_SCRIPT).write_text(
            render_launch_script(self.command(run)), encoding="utf-8", newline="\n"
        )
        return PreparedTrainingRun(
            run=run,
            backend=self.name,
            workdir=str(workdir),
            command=("bash", LAUNCH_SCRIPT),
            files=("data/prompts.jsonl", "reward_func.py", RUN_CONFIG_FILE, LAUNCH_SCRIPT),
            framework_version=framework_version("openrlhf"),
            notes=(
                f"target OpenRLHF {TARGET_OPENRLHF_VERSION} (dotted flags); requires a Ray cluster",
                "confirm flags with `python3 -m openrlhf.cli.train_ppo_ray --help` on the GPU host",
            ),
        )

    def launch(self, run: PreparedTrainingRun) -> TrainingHandle:
        return remote_only_launch(run, "OpenRLHF")

    def inspect(self, handle: TrainingHandle) -> TrainingStatus:
        return status_from_workdir(handle)
