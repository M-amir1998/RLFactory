"""Training backend protocol and the run-directory conventions every backend shares.

A prepared run directory is self-contained (config, data, launch script) so it can be synced to a
GPU host as-is. While running, backends write:

* ``status.json``           - :class:`TrainingStatus` (state, step, error)
* ``metrics.jsonl``         - one :class:`TrainingMetricsPoint` per logging step
* ``training_summary.json`` - :class:`TrainingSummary` at the end
* ``exit_status.json``      - written by ``launch.sh`` for any framework, even without hooks
"""

from __future__ import annotations

import json
import shlex
from collections.abc import Callable, Mapping, Sequence
from pathlib import Path
from typing import Protocol

from rlfactory.config.loader import read_json_model, write_json
from rlfactory.domain.training import (
    CheckpointEvent,
    PreparedTrainingRun,
    TrainingHandle,
    TrainingMetricsPoint,
    TrainingRun,
    TrainingState,
    TrainingStatus,
)
from rlfactory.errors import ConfigError, RegistryError

STATUS_FILE = "status.json"
METRICS_FILE = "metrics.jsonl"
SUMMARY_FILE = "training_summary.json"
RUN_CONFIG_FILE = "run_config.json"
LAUNCH_SCRIPT = "launch.sh"
EXIT_STATUS_FILE = "exit_status.json"
PREPARED_FILE = "prepared.json"


class TrainingBackend(Protocol):
    name: str

    def prepare(self, run: TrainingRun) -> PreparedTrainingRun: ...

    def launch(self, run: PreparedTrainingRun) -> TrainingHandle: ...

    def inspect(self, handle: TrainingHandle) -> TrainingStatus: ...


def save_prepared(prepared: PreparedTrainingRun) -> PreparedTrainingRun:
    """Persist the prepared run so remote tooling and resumes can reload it."""
    write_json(prepared, Path(prepared.workdir) / PREPARED_FILE)
    return prepared


def load_prepared(workdir: Path) -> PreparedTrainingRun:
    return read_json_model(workdir / PREPARED_FILE, PreparedTrainingRun)


def write_status(workdir: Path, status: TrainingStatus) -> None:
    write_json(status, workdir / STATUS_FILE)


def read_status(workdir: Path) -> TrainingStatus | None:
    path = workdir / STATUS_FILE
    if not path.exists():
        return None
    try:
        return read_json_model(path, TrainingStatus)
    except ConfigError:
        return None


def append_metrics(workdir: Path, point: TrainingMetricsPoint) -> None:
    with (workdir / METRICS_FILE).open("a", encoding="utf-8", newline="\n") as handle:
        handle.write(point.model_dump_json() + "\n")


def read_metrics(workdir: Path) -> list[TrainingMetricsPoint]:
    path = workdir / METRICS_FILE
    if not path.exists():
        return []
    return [
        TrainingMetricsPoint.model_validate_json(line)
        for line in path.read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]


def status_from_workdir(handle: TrainingHandle) -> TrainingStatus:
    """Best-effort status for any backend from the shared run-directory files."""
    workdir = Path(handle.workdir)
    status = read_status(workdir)
    if status is not None:
        return status
    exit_path = workdir / EXIT_STATUS_FILE
    if exit_path.exists():
        code = int(json.loads(exit_path.read_text(encoding="utf-8")).get("exit_code", 1))
        metrics = read_metrics(workdir)
        return TrainingStatus(
            handle_id=handle.handle_id,
            state=TrainingState.SUCCEEDED if code == 0 else TrainingState.FAILED,
            step=metrics[-1].step if metrics else 0,
            latest=metrics[-1] if metrics else None,
            error=None if code == 0 else f"launcher exited with code {code}",
        )
    return TrainingStatus(handle_id=handle.handle_id, state=TrainingState.PREPARED)


def render_launch_script(
    command: Sequence[str], environment: Mapping[str, str] | None = None
) -> str:
    """POSIX launcher: runs ``command`` in the script's directory, tees output to ``train.log``,
    and records the exit code in ``exit_status.json``. Never embeds secrets: only names given in
    ``environment`` are exported, and callers must not pass credential values."""
    lines = [
        "#!/usr/bin/env bash",
        "# Generated by RLFactory. Review before running on a GPU host.",
        "set -uo pipefail",
        'cd "$(dirname "$0")"',
    ]
    for key, value in sorted((environment or {}).items()):
        lines.append(f"export {key}={shlex.quote(value)}")
    lines += [
        f"{shlex.join(command)} 2>&1 | tee -a train.log",
        "code=${PIPESTATUS[0]}",
        (
            'printf \'{"exit_code": %d, "finished_at": "%s"}\\n\' "$code" '
            '"$(date -u +%Y-%m-%dT%H:%M:%SZ)" > exit_status.json'
        ),
        'exit "$code"',
        "",
    ]
    return "\n".join(lines)


def checkpoint_events(workdir: Path) -> tuple[CheckpointEvent, ...]:
    status = read_status(workdir)
    return status.checkpoints if status is not None else ()


BackendFactory = Callable[[Path], TrainingBackend]


class TrainingBackendRegistry:
    def __init__(self) -> None:
        self._factories: dict[str, BackendFactory] = {}

    def register(self, name: str, factory: BackendFactory) -> None:
        if name in self._factories:
            raise RegistryError(f"training backend {name!r} already registered")
        self._factories[name] = factory

    def names(self) -> list[str]:
        return sorted(self._factories)

    def create(self, name: str, workdir_root: Path) -> TrainingBackend:
        try:
            return self._factories[name](workdir_root)
        except KeyError as exc:
            raise RegistryError(
                f"unknown training backend {name!r}; known: {', '.join(self.names())}"
            ) from exc


def default_backend_registry() -> TrainingBackendRegistry:
    from rlfactory.training.mock.backend import MockTrainingBackend
    from rlfactory.training.openrlhf.backend import OpenRLHFTrainingBackend
    from rlfactory.training.trl.backend import TRLTrainingBackend
    from rlfactory.training.verl.backend import VerlTrainingBackend

    registry = TrainingBackendRegistry()
    registry.register("mock", MockTrainingBackend)
    registry.register("trl", TRLTrainingBackend)
    registry.register("verl", VerlTrainingBackend)
    registry.register("openrlhf", OpenRLHFTrainingBackend)
    return registry
